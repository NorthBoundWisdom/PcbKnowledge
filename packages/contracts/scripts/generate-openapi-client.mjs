import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const sourcePath = resolve(
  repositoryRoot,
  "packages/contracts/openapi/pcbknowledge.openapi.json",
);
const outputDirectory = resolve(
  repositoryRoot,
  "apps/curator-web/src/api/generated",
);

const args = new Set(process.argv.slice(2));
const unknownArgs = [...args].filter((argument) => argument !== "--check");
if (unknownArgs.length > 0) {
  console.error(`Unknown argument(s): ${unknownArgs.join(", ")}`);
  process.exitCode = 2;
} else {
  await generate({ check: args.has("--check") });
}

async function generate({ check }) {
  const sourceBytes = await readFile(sourcePath);
  const sourceSha256 = createHash("sha256").update(sourceBytes).digest("hex");
  const schema = JSON.parse(sourceBytes.toString("utf8"));
  const schemaAst = await openapiTS(schema, {
    alphabetize: true,
    exportType: true,
  });

  const banner = `/**\n * @generated by packages/contracts/scripts/generate-openapi-client.mjs\n * Source: packages/contracts/openapi/pcbknowledge.openapi.json\n * Source SHA-256: ${sourceSha256}\n * Do not edit by hand.\n */\n`;
  const outputs = new Map([
    ["schema.d.ts", `${banner}${astToString(schemaAst)}`],
    [
      "client.ts",
      `${banner}\nimport createClient, { type Client } from "openapi-fetch";\n\nimport type { paths } from "./schema";\n\nexport type GeneratedApiClient = Client<paths>;\n\nexport function createGeneratedApiClient(baseUrl: string): GeneratedApiClient {\n  return createClient<paths>({ baseUrl });\n}\n`,
    ],
    [
      "index.ts",
      `${banner}\nexport { createGeneratedApiClient, type GeneratedApiClient } from "./client";\nexport type { components, operations, paths } from "./schema";\n\nexport const generatedContractSha256 = "${sourceSha256}" as const;\n`,
    ],
  ]);

  if (check) {
    const drifted = [];
    for (const [relativePath, expected] of outputs) {
      const outputPath = resolve(outputDirectory, relativePath);
      let actual;
      try {
        actual = await readFile(outputPath, "utf8");
      } catch (error) {
        if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
          drifted.push(`${relativePath} (missing)`);
          continue;
        }
        throw error;
      }

      if (actual !== expected) {
        drifted.push(relativePath);
      }
    }

    if (drifted.length > 0) {
      console.error(`Generated OpenAPI client drift detected: ${drifted.join(", ")}`);
      console.error("Run `pnpm generate:api` and commit the generated outputs.");
      process.exitCode = 1;
      return;
    }

    console.log(`Generated OpenAPI client is current (${sourceSha256}).`);
    return;
  }

  await mkdir(outputDirectory, { recursive: true });
  for (const [relativePath, contents] of outputs) {
    await writeFile(resolve(outputDirectory, relativePath), contents, "utf8");
  }
  console.log(`Generated OpenAPI client from ${sourceSha256}.`);
}
